export function injectMissingSectionFields(entityType: string, schemaFields: FormField[]): FormField[] {
  const defaultSections = DEFAULT_SECTION_FIELDS[normalizeEntityType(entityType)] || [];
  if (defaultSections.length === 0) return schemaFields;
  const missingSections = defaultSections.filter(
    (defaultField) => !schemaFields.some((f) => f.id === defaultField.id)
  );
  if (missingSections.length === 0) return schemaFields;
  return [...schemaFields, ...missingSections];
}

export function getSchemaFieldsForEntity(schemas: FormSchema[], entityType: string): FormField[] {
  const normalizedEntityType = normalizeEntityType(entityType);
  const schema = schemas.find(
    (s) => normalizeEntityType(s.entity_type) === normalizedEntityType && s.is_active
  );
  return schema?.schema?.fields?.filter((f) => f.type !== 'section' && f.type !== 'reference') || [];
}
