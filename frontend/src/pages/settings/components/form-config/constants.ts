/**
 * Field types that cannot be used as a picklist_multi extension field:
 * `section`, `picklist_multi`, `reference`, `auto_number`, `timer_duration`.
 *
 * `section` is a layout placeholder with no value; `picklist_multi` would nest a
 * wizard inside a wizard; `reference`, `auto_number` and `timer_duration` are
 * resolved or generated by the backend per record, which it can only do for a
 * top-level entity field, not for a value nested inside one.
 *
 * `document` IS supported — do not add it back here. `EntitiesServiceManager.
 * _validate_extension_document_values` walks each row's `extensions`, and
 * `_read_option_document_values` claims an option's files under the nested key
 * `<field>.<option>.<extension field id>`, so a file uploaded before the record
 * exists is handed to `_attach_unowned_document_files` like a top-level one.
 */
export const EXTENSION_DISALLOWED_TYPES: readonly FieldType[] = [
  'section',
  'picklist_multi',
  'reference',
  'auto_number',
  'timer_duration',
];

