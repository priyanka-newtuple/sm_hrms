import type { FieldType, FormField, FormSchema } from '../../../../core/types';

export function toFieldId(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

export function normalizeEntityType(value: string): string {
  return value.trim();
}

const FIELD_ID_SUFFIX_START = 2;

export function generateFieldId(label: string, existingFields: FormField[], excludeIndex: number): string {
  const base = toFieldId(label) || 'field';
  let candidate = base;
  let counter = FIELD_ID_SUFFIX_START;
  while (existingFields.some((f, i) => f.id === candidate && (excludeIndex === -1 || i !== excludeIndex))) {
    candidate = `${base}_${counter++}`;
  }
  return candidate;
}

